let audioRequests: string[];
let regenerateCalls: number;

function jsonRes(body: unknown, status = 200) {
  return { ok: status >= 200 && status < 300, status, json: async () => body };
}

function installFetch() {
  vi.stubGlobal(
    'fetch',
    vi.fn(async (input: RequestInfo | URL, init?: RequestInit) => {
      const url = String(input);
      if (url.includes('/audio')) {
        audioRequests.push(url);
        return {
          ok: true,
          status: 200,
          headers: { get: () => 'audio/webm' },
          arrayBuffer: async () => new ArrayBuffer(2048),
        };
      }
      if (url.includes('/transcript')) {
        return jsonRes({
          segments: [
            { id: 'seg-1', text: '开场白', globalStartMs: 0, globalEndMs: 5_000, startMs: 0, endMs: 5_000 },
            { id: 'seg-2', text: '第二个要点', globalStartMs: 120_000, globalEndMs: 125_000, startMs: 120_000, endMs: 125_000 },
          ],
          summaries: [],
        });
      }
      if (url.includes('/api/llm/report')) return jsonRes({ report: REPORT });
      if (url.includes('/enhance-status')) {
        return jsonRes({ available: true, status: 'completed', enhancedAudioReady: true });
      }
      if (url.includes('/regenerate-title') && init?.method === 'POST') {
        regenerateCalls += 1;
        return jsonRes({ success: true, title: '新标题', titleEn: 'New title' });
      }
      if (url.includes('/api/user/background-tasks')) return jsonRes({ jobs: [] });
      if (url.endsWith('/api/sessions/s1')) return jsonRes(SESSION);
      return jsonRes({});
    })
  );
}

// jsdom 不加载媒体：所有 <audio> 的 duration 读成 600s，并在创建后自动派发 loadedmetadata
// （模拟浏览器加载完元数据；探测时长的临时元素与页面上的播放器元素都走这条路径）。
const originalDuration = Object.getOwnPropertyDescriptor(window.HTMLMediaElement.prototype, 'duration');
const originalCreateElement = document.createElement.bind(document);
function autoLoadAudioMetadata() {
  vi.spyOn(document, 'createElement').mockImplementation(((tagName: string, options?: ElementCreationOptions) => {
    const element = originalCreateElement(tagName, options);
    if (tagName.toLowerCase() === 'audio') {
      setTimeout(() => element.dispatchEvent(new Event('loadedmetadata')), 0);
    }
    return element;
  }) as typeof document.createElement);
}

describe('回放页', () => {
  beforeEach(() => {
    memStorage.clear();
    audioRequests = [];
    regenerateCalls = 0;
    mobileMocks.isMobile = false;
    Object.defineProperty(window.HTMLMediaElement.prototype, 'duration', {
      configurable: true,
      get: () => 600,
    });
    vi.spyOn(window.HTMLMediaElement.prototype, 'load').mockImplementation(() => {});
    useAuthStore.setState({
      user: { id: 'u-1', email: 'u@test', displayName: 'U', role: 'PRO' } as never,
      token: 'test-token',
      quotas: null,
    });
    installFetch();
  });

  afterEach(() => {
    cleanup();
    vi.useRealTimers();
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
    if (originalDuration) {
      Object.defineProperty(window.HTMLMediaElement.prototype, 'duration', originalDuration);
    }
  });

  it('#7：切换「原声/增强」音源后回到切换前的播放进度，并在新音频加载后 seek 回去', async () => {
    autoLoadAudioMetadata();
    const user = userEvent.setup();
    const { container } = render(<PlaybackPage />);

    await waitFor(() => {
      expect(screen.getByText('第二个要点')).toBeInTheDocument();
    });
    // 默认加载增强版，探测完时长后音频元素挂上
    await waitFor(() => {
      expect(container.querySelector('audio')).not.toBeNull();
    });
    expect(audioRequests).toHaveLength(1);
    expect(audioRequests[0]).toContain('variant=enhanced');
    const firstAudio = container.querySelector('audio') as HTMLAudioElement;

    // 跳到 2:00
    await user.click(screen.getByText('第二个要点'));
    expect(screen.getByTestId('playback-current-time')).toHaveTextContent('00:02:00');
    expect(firstAudio.currentTime).toBe(120);

    // 切到原声：重新拉原声音频，新 <audio> 元素加载完元数据后应 seek 回 120s
    await user.click(screen.getByTestId('audio-original'));
    await waitFor(() => {
      expect(audioRequests).toHaveLength(2);
    });
    expect(audioRequests[1]).not.toContain('variant=enhanced');
    await waitFor(() => {
      const audio = container.querySelector('audio');
      expect(audio).not.toBeNull();
      expect(audio).not.toBe(firstAudio);
      expect((audio as HTMLAudioElement).currentTime).toBe(120);
    });
    expect(screen.getByTestId('playback-current-time')).toHaveTextContent('00:02:00');
  });

  it('#8：移动端「信息」页点「重新生成标题」会弹出确认框，确认后才真正请求', async () => {
    mobileMocks.isMobile = true;
    const user = userEvent.setup();
    render(<PlaybackPage />);

    await waitFor(() => {
      expect(screen.getAllByText('线性代数 第三讲').length).toBeGreaterThan(0);
    });

    await user.click(screen.getByText('playback.tabInfo'));
    await user.click(screen.getByRole('button', { name: 'playback.regenerateTitle' }));

    const dialog = await screen.findByRole('dialog');
    expect(within(dialog).getByText('playback.regenerateTitleConfirm')).toBeInTheDocument();
    expect(regenerateCalls).toBe(0);

    await user.click(within(dialog).getByRole('button', { name: 'playback.regenerateTitle' }));
    await waitFor(() => {
      expect(regenerateCalls).toBe(1);
    });
  });
});
