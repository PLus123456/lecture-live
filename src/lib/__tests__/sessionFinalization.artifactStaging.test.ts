/**
 * M5 + L20：收尾产物的两阶段提交必须覆盖**全部三类**产物（录音 / 转录 / 摘要），
 * 且回滚必须覆盖**全部未提交路径**（CAS 输了 + 事务自身抛错）。
 *
 * M5（旧洞）：P0-6 的 stage→CAS→publish/rollback 只给了录音，转录/摘要仍走
 * persistSessionTranscriptArtifacts 写**固定 key** `{id}.json`，且写在 CAS 事务之前。
 * finalizer A 因大文件 ffmpeg 超过 FINALIZE_LOCK_STALE_MS(15min) 被 B 接管时：B 先提交自己的
 * bundle，A 随后 count===0 走 lockLost —— 旧代码只 rollback stagedAudio，A 覆盖掉的那份固定 key
 * 转录/摘要**原地不动**，而 DB 指向的正是这个 path ⇒ 最终存储的转录 ≠ 提交时审计的转录。
 *
 * L20（旧洞）：`$transaction` 自身抛错（死锁/锁等待超时/连接断开）时 CAS 从未生效，
 * 但 stage 出的版本化文件（本地 + 可能的 Cloudreve 远程副本）已经落盘 —— 旧代码只有 lockLost
 * 分支回滚，这条路径把它们漏成无主孤儿（无任何 DB 行引用，删会话时也扫不到）。
 *
 * 反向契约（同样要锁住）：CAS **提交之后**再抛错，绝不能回滚 —— 那会删掉刚定稿的录音/转录。
 */

