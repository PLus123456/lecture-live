describe('finalizeSession — M5：转录/摘要走 stage → CAS → publish 两阶段', () => {
  it('▶ CAS 赢：写库的是版本化引用（非固定 key {id}.json），提交后三类产物全部 publish', async () => {
    const res = await finalizeSession({ sessionId: 'sess-1', actor: null });

    expect(stageTranscriptMock).toHaveBeenCalledTimes(1);
    // 写进 CAS 事务的 path 必须是 stage 出来的版本化引用 —— 旧实现写的是被并发 finalizer
    // 覆盖过的固定 key。
    expect(txSessionUpdateManyMock.mock.calls[0][0].data).toMatchObject({
      status: 'COMPLETED',
      recordingPath: STAGED_AUDIO.reference,
      transcriptPath: STAGED_TRANSCRIPT.reference,
      summaryPath: STAGED_SUMMARY.reference,
    });
    expect(res.transcriptPath).toBe(STAGED_TRANSCRIPT.reference);
    expect(res.summaryPath).toBe(STAGED_SUMMARY.reference);

    // 提交之后才发布，且三类一次性交给 completeStagedArtifactPublishes
    // （转录/摘要无 previousReference，publish 是纯语义调用）。
    expect(publishMock).toHaveBeenCalledTimes(1);
    const published = (
      publishMock.mock.calls[0][1] as Array<{ staged: { reference: string } }>
    )
      .map((entry) => entry.staged.reference)
      .sort();
    expect(published).toEqual(
      [
        STAGED_AUDIO.reference,
        STAGED_TRANSCRIPT.reference,
        STAGED_SUMMARY.reference,
      ].sort()
    );
    expect(rollbackMock).not.toHaveBeenCalled();
  });

  it('▶ M5 lockLost（锁被接管者先提交）：转录与摘要**也**被回滚，不只回滚录音', async () => {
    txSessionUpdateManyMock.mockResolvedValueOnce({ count: 0 }); // 锁已被 B 接管
    sessionFindUniqueMock.mockResolvedValue(SESSION);

    const res = await finalizeSession({ sessionId: 'sess-1', actor: null });

    expect(res.alreadyCompleted).toBe(true);
    // ▶ 旧实现这里只有 recordings 一条 —— transcripts/summaries 留在固定 key 上覆盖了 B 的产物。
    expect(rolledBack()).toEqual(
      [
        STAGED_AUDIO.reference,
        STAGED_TRANSCRIPT.reference,
        STAGED_SUMMARY.reference,
      ].sort()
    );
    // CAS 没生效 → 一个都不许 publish。
    expect(publishMock).not.toHaveBeenCalled();
  });
});

describe('finalizeSession — L20：事务抛错路径也要清 staged', () => {
  it('▶ $transaction 抛错（死锁/超时）：三类 staged 全部回滚，错误照常上抛', async () => {
    transactionMock.mockRejectedValueOnce(
      Object.assign(new Error('Deadlock found when trying to get lock'), {
        code: 'P2034',
      })
    );

    await expect(
      finalizeSession({ sessionId: 'sess-1', actor: null })
    ).rejects.toThrow(/Deadlock/);

    // ▶ 旧实现：lockLost 有 rollback，事务抛错这条路径一个都不删 → 版本化文件成无主孤儿。
    expect(rolledBack()).toEqual(
      [
        STAGED_AUDIO.reference,
        STAGED_TRANSCRIPT.reference,
        STAGED_SUMMARY.reference,
      ].sort()
    );
    expect(publishMock).not.toHaveBeenCalled();
  });

  it('▶ 反向契约：CAS 已提交之后再抛错，绝不回滚（否则删掉刚定稿的产物）', async () => {
    // CAS 赢（count=1）但事务内回读 updated 为 null → 提交之后访问 updatedSession.title 抛 TypeError。
    txSessionUpdateManyMock.mockResolvedValueOnce({ count: 1 });
    txSessionFindUniqueMock.mockResolvedValueOnce(null);

    await expect(
      finalizeSession({ sessionId: 'sess-1', actor: null })
    ).rejects.toBeInstanceOf(TypeError);

    expect(rollbackMock).not.toHaveBeenCalled();
    // 提交后的发布照常发生（发布在抛错点之前）。
    expect(publishMock).toHaveBeenCalled();
  });
});
